// node audio.js <out.wav> [seconds]  renders the soundtrack offline in Chromium (env CUT picks the track)
const { chromium } = require('playwright')
const fs = require('fs')
;(async () => {
  const out = process.argv[2], secs = +(process.argv[3] || 40)
  const b = await chromium.launch()
  const p = await b.newPage()
  p.on('pageerror', (e) => console.log('pageerror', e.message))
  await p.goto('http://127.0.0.1:8811/comp/audio.html?cut=' + (process.env.CUT || 'main'))
  const b64 = await p.evaluate((s) => window.renderAudio(s), secs)
  const pcm = Buffer.from(b64, 'base64')
  const h = Buffer.alloc(44)
  h.write('RIFF', 0); h.writeUInt32LE(36 + pcm.length, 4); h.write('WAVE', 8); h.write('fmt ', 12)
  h.writeUInt32LE(16, 16); h.writeUInt16LE(1, 20); h.writeUInt16LE(2, 22); h.writeUInt32LE(48000, 24)
  h.writeUInt32LE(48000 * 4, 28); h.writeUInt16LE(4, 32); h.writeUInt16LE(16, 34); h.write('data', 36); h.writeUInt32LE(pcm.length, 40)
  fs.writeFileSync(out, Buffer.concat([h, pcm]))
  await b.close()
  console.log('wrote', out)
})()
